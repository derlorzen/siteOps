CREATE TABLE IF NOT EXISTS mail_log (
  id CHAR(36) NOT NULL PRIMARY KEY,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  completed_at DATETIME(3) NULL,
  source VARCHAR(32) NOT NULL,
  reference_id VARCHAR(191) NULL,
  sender VARCHAR(500) NOT NULL,
  recipients TEXT NOT NULL,
  cc TEXT NOT NULL,
  bcc TEXT NOT NULL,
  subject VARCHAR(500) NOT NULL,
  attachment_names TEXT NOT NULL,
  attachment_count SMALLINT UNSIGNED NOT NULL DEFAULT 0,
  status ENUM('sending','accepted','failed','partial') NOT NULL DEFAULT 'sending',
  message_id VARCHAR(255) NULL,
  smtp_code SMALLINT UNSIGNED NULL,
  error_code VARCHAR(40) NULL,
  accepted_count SMALLINT UNSIGNED NOT NULL DEFAULT 0,
  rejected_count SMALLINT UNSIGNED NOT NULL DEFAULT 0,
  KEY idx_mail_created (created_at,id),
  KEY idx_mail_status_created (status,created_at),
  KEY idx_mail_source_created (source,created_at),
  KEY idx_mail_reference (reference_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
